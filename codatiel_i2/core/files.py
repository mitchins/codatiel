"""Changed-file classification (lifted from Iteration 1, expanded).

Source: tools/codatiel_file_filter.py — categories and exclusion logic lifted,
then expanded to the Iteration-2 taxonomy with 100% changed-file accounting.

Iteration-2 categories (12):
source, test, config, docs, schema, migration, generated, lockfile,
vendored, binary, snapshot, unknown

Every changed file appears in the outputExactly once. Nothing is silently
discarded: excluded files are recorded with include=False and a reason.
"""

from __future__ import annotations

from pathlib import Path, PurePosixPath

CATEGORIES = (
    "source", "test", "config", "docs", "schema", "migration",
    "generated", "lockfile", "vendored", "binary", "snapshot", "unknown",
)

SCHEMA_VERSION = "codatiel_i2.file_classification.v1"

LOCKFILE_NAMES = {
    "Cargo.lock", "Pipfile.lock", "bun.lockb", "package-lock.json",
    "pnpm-lock.yaml", "poetry.lock", "yarn.lock", "Gemfile.lock",
}

GENERATED_SUFFIXES = (".min.js", ".map", ".generated.ts", ".gen.py", ".pb.go")
GENERATED_MARKERS = ("@generated", "generated by", "do not edit", "auto-generated", "autogenerated")

VENDORED_DIRS = {"node_modules", "vendor", "third_party", "Pods", ".venv", "venv", "env", ".tox"}

MIGRATION_DIRS = {"migrations", "migration", "db/migrations", "schema_migrations", "alembic"}

TEST_DIRS = {"tests", "test", "__tests__", "fixtures", "e2e"}

CONFIG_NAMES = {
    "package.json", "pyproject.toml", "ruff.toml", ".ruff.toml", "biome.json",
    "biome.jsonc", "tsconfig.json", "jsconfig.json", ".eslintrc.json",
    "codatiel.yaml", "codatiel.yml", "setup.cfg", "requirements.txt",
    "requirements-dev.txt", "requirements-test.txt", "cmakelists.txt",
}

CONFIG_BASENAMES = {
    "dockerfile", "makefile", "cmakelists.txt", ".gitignore", ".dockerignore",
}

# Certainty scale (heuristic, uncalibrated): 0.95 lockfile/binary (name/ext),
# 0.9 vendored path, 0.85 generated markers, 0.8 default, 0.4 unknown name.
# Emitted as generated_certainty/binary_certainty; other categories carry the
# same value in `certainty` for future calibration.

DOCS_EXTS = {".md", ".mdx", ".rst", ".adoc"}
DOCS_DIRS = {"docs", "documentation", "wiki", "man"}

SCHEMA_EXTS = {".jsonschema", ".avsc", ".proto", ".graphql", ".gql"}
SCHEMA_NAMES = {"openapi.json", "openapi.yaml", "openapi.yml", "swagger.json", "schema.json"}

SNAPSHOT_DIRS = {"__snapshots__", "snapshots", "testdata", "fixtures/snapshots"}
SNAPSHOT_SUFFIXES = (".snap", ".snapshot", ".snap.json")

BINARY_EXTS = {
    ".png", ".jpg", ".jpeg", ".gif", ".webp", ".ico", ".pdf", ".zip", ".tar",
    ".gz", ".bz2", ".xz", ".exe", ".dll", ".so", ".dylib", ".class", ".o",
    ".a", ".woff", ".woff2", ".ttf", ".otf", ".mp4", ".mov", ".sqlite", ".db",
}

LANGUAGE_BY_EXT = {
    ".py": "python", ".js": "javascript", ".jsx": "javascript", ".ts": "typescript",
    ".tsx": "typescript", ".go": "go", ".rs": "rust", ".java": "java",
    ".kt": "kotlin", ".swift": "swift", ".rb": "ruby", ".php": "php",
    ".c": "c", ".h": "c", ".cc": "cpp", ".cpp": "cpp", ".hpp": "cpp",
    ".cs": "csharp", ".sh": "shell", ".yaml": "yaml", ".yml": "yaml",
    ".json": "json", ".toml": "toml", ".md": "markdown", ".sql": "sql",
}

DETECTOR_HINTS = {
    # Routing hints only (never applicability decisions). Known limits:
    # authorization/operating_constraints route from source only — a
    # config-surface RBAC/timeout change will not auto-suggest them;
    # semantic_twins from source/test only; snapshot only contracts;
    # generated/lockfile/vendored/binary/unknown route nowhere.
    # classify_file("x.bin") without is_binary=True mis-hints: callers
    # must thread binary detection (cli.py does via numstat).
    "source": ["contracts", "authorization", "docs_code", "operating_constraints", "semantic_twins"],
    "test": ["semantic_twins"],
    "config": ["contracts", "docs_code"],
    "docs": ["docs_code"],
    "schema": ["contracts", "docs_code"],
    "migration": ["contracts", "docs_code"],
    "generated": [],
    "lockfile": [],
    "vendored": [],
    "binary": [],
    "snapshot": ["contracts"],
    "unknown": [],
}


def classify_file(path: str, *, content_hint: str | None = None,
                  additions: int = 0, deletions: int = 0,
                  is_binary: bool = False) -> dict:
    rel = path.replace("\\", "/").strip()
    if rel.startswith("./"):
        rel = rel[2:]
    rel = rel.lstrip("/")
    posix = PurePosixPath(rel)
    name = posix.name
    lower = rel.lower()
    parts = [p.lower() for p in posix.parts]
    ext = posix.suffix.lower()

    category = "source"
    reason = "source"
    include = True
    certainty = 0.8

    if is_binary or ext in BINARY_EXTS:
        category, reason, include, certainty = "binary", "binary", False, 0.95
    elif name in LOCKFILE_NAMES:
        category, reason, include, certainty = "lockfile", "lockfile", False, 0.95
    elif any(part.lower() in VENDORED_DIRS for part in posix.parts):
        category, reason, include, certainty = "vendored", "vendored", False, 0.9
    elif any(lower.endswith(s) for s in GENERATED_SUFFIXES) or (
        content_hint and any(m in content_hint.lower()[:2000] for m in GENERATED_MARKERS)
    ):
        category, reason, include, certainty = "generated", "generated", False, 0.85
    elif "migrations" in parts or "migration" in parts or name.endswith(("_migration.py", ".migration.py")):
        category, reason = "migration", "migration"
    elif any(part in ("__snapshots__", "snapshots", "testdata") for part in parts) or any(lower.endswith(s) for s in SNAPSHOT_SUFFIXES):
        category, reason = "snapshot", "snapshot"
    elif ext in DOCS_EXTS or any(part in DOCS_DIRS for part in parts):
        category, reason = "docs", "docs"
    elif ext in SCHEMA_EXTS or name in SCHEMA_NAMES or "schema" in parts or "schemas" in parts:
        category, reason = "schema", "schema"
    elif _is_test_path(posix):
        category, reason = "test", "test"
    elif _is_config_path(posix, rel):
        category, reason = "config", "config"
    elif not name or name.startswith(".") and ext == "":
        category, reason, certainty = "unknown", "unknown_name", 0.4

    language = LANGUAGE_BY_EXT.get(ext, "unknown")
    token_cost = estimate_tokens(additions, deletions)
    return {
        "path": rel,
        "category": category,
        "include": include,
        "reason": reason,
        "language": language,
        "additions": additions,
        "deletions": deletions,
        "estimated_tokens": token_cost,
        "detectors": DETECTOR_HINTS.get(category, []),
        "certainty": certainty,
        "generated_certainty": certainty if category == "generated" else 0.0,
        "binary_certainty": certainty if category == "binary" else 0.0,
    }


def _is_test_path(posix: PurePosixPath) -> bool:
    parts = [p.lower() for p in posix.parts]
    if any(p in TEST_DIRS for p in parts):
        return True
    name = posix.name.lower()
    return (name.startswith("test_") or name.endswith("_test.py")
            or name.endswith(".spec.ts") or name.endswith(".spec.js")
            or name.endswith(".test.ts") or name.endswith(".test.js"))


def _is_config_path(posix: PurePosixPath, rel: str) -> bool:
    if posix.name in CONFIG_NAMES or posix.name.lower() in CONFIG_BASENAMES:
        return True
    lower = rel.lower()
    base = lower.rsplit("/", 1)[-1]
    if base.startswith(".env"):
        return True
    return lower.startswith(".github/workflows/") or lower.endswith((".yaml", ".yml", ".toml", ".ini", ".cfg"))


def estimate_tokens(additions: int, deletions: int) -> int:
    # Rough heuristic: ~4 chars/token, ~40 chars/line.
    return int((additions + deletions) * 10)


def classify_changes(changes: list[dict], content_hints: dict[str, str] | None = None,
                     binary_paths: set[str] | None = None) -> dict:
    """Classify every changed file. Guarantees 100% accounting."""
    content_hints = content_hints or {}
    binary_paths = binary_paths or set()
    files = []
    for row in changes:
        try:
            files.append(classify_file(
                row["path"],
                content_hint=content_hints.get(row["path"]),
                additions=row.get("additions", 0),
                deletions=row.get("deletions", 0),
                is_binary=row["path"] in binary_paths or bool(row.get("is_binary")),
            ))
        except Exception:
            files.append({
                "path": str(row.get("path", "unknown")),
                "category": "unknown",
                "include": True,
                "reason": "classify_error",
                "language": "unknown",
                "additions": row.get("additions", 0) if isinstance(row, dict) else 0,
                "deletions": row.get("deletions", 0) if isinstance(row, dict) else 0,
                "estimated_tokens": 0,
                "detectors": [],
                "certainty": 0.0,
                "generated_certainty": 0.0,
                "binary_certainty": 0.0,
            })
    by_category: dict[str, int] = {}
    for f in files:
        by_category[f["category"]] = by_category.get(f["category"], 0) + 1
    return {
        "schema_version": SCHEMA_VERSION,
        "total_changed": len(changes),
        "classified": len(files),
        "accounting_complete": len(files) == len(changes),
        "by_category": by_category,
        "files": sorted(files, key=lambda r: r["path"]),
    }
